/**
 * Team colors, generated once from ESPN's team lists (none of our MLB or NHL
 * Sources publish colors; college football covers every FBS team). Keyed
 * by League and normalized team name, so they apply whichever Source named
 * the Team. Regenerate when a franchise rebrands.
 */

import type { League } from '@/lib/model/types'

export interface TeamColors {
  primary: string
  secondary: string
}

/** Lower case, no accents or punctuation: "Montréal Canadiens" → "montreal canadiens". */
export function normalizeTeamName(name: string): string {
  return name
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9 ]/g, '')
    .replace(/\s+/g, ' ')
    .trim()
}

